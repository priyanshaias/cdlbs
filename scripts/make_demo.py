"""Makes docs/js/demo-data.js: ~180 DL/CDL people from 4 divisions of the cleaned data, with MADE-UP names.
Ranges, beats, duties, pay and missing fields follow the real records so the demo behaves like the real thing.
Run: python3 scripts/make_demo.py <CDL/Cleaning folder>"""
import sys, os, json, random, re
sys.path.insert(0, os.path.dirname(__file__))
import duty_classify as K

random.seed(7)
K.SRC = sys.argv[1]
OUT = os.path.join(os.path.dirname(__file__), '..', 'docs', 'js', 'demo-data.js')

# cleaned-data division -> (UPMC circle, UPMC division, ranges to take or None for all)
PICK = {'Purulia': ('South West', 'Purulia', ['Ajodhya', 'Joypur']),
        'Jaldapara WL': ('Wild Life North', 'Jaldapara WL', ['Chilapata', 'CTTL']),
        'Bankura (North)': ('Central', 'Bankura (N)', None),
        'Jhargram': ('Western', 'Jhargram', ['AFR', 'Jhargram'])}

DUTY = {  # sub-category from the classifier -> one of the 9 duty categories
 'Cleaning / sweeping': 'Cleaning/Sweeping/Maintenance', 'Maintenance & utilities': 'Cleaning/Sweeping/Maintenance', 'Rest house / bungalow': 'Cleaning/Sweeping/Maintenance',
 'Nursery': 'Nursery Operations', 'Plantation work': 'Nursery Operations', 'Timber depot': 'Timber Depot', 'Driver': 'Driver', 'Garden / park': 'Mali/Gardener',
 'Patrolling & forest protection': 'Forest Protection and Patrolling', 'Plantation watch & ward': 'Forest Protection and Patrolling',
 'Check post / gate': 'Forest Protection and Patrolling', 'Fire / watch tower': 'Forest Protection and Patrolling',
 'Elephant / wildlife conflict': 'Human-Animal Conflict Management', 'Wildlife rescue & release': 'Human-Animal Conflict Management',
 'Night guard / security': 'Night Guard/Security'}
PLACE = {'Beat': 'Beat', 'Range HQ': 'Range office', 'Range (beat not stated)': 'Range office', 'Division HQ': 'Division office', 'Timber depot': 'Timber depot', 'Rest house': 'Rest house'}

FIRST = 'Amit Ajoy Anil Bablu Bapi Bijoy Biswajit Debu Dilip Gopal Haradhan Jagannath Kartik Laxman Madan Manik Nimai Nitai Pintu Prasanta Rabin Rajesh Ratan Samir Sanjay Shankar Sujit Tapan Uttam Bimala Champa Kalpana Lakshmi Mamata Minati Purnima Sabita Sandhya Shefali'.split()
LAST = 'Mahato Murmu Hansda Soren Tudu Kisku Bauri Mandi Oraon Roy Barman Das Mondal Singh Sardar Bag Ghosh Pal Majhi Hembram Baskey Lohar Rabha Toto Sarkar'.split()
def name():
    return random.choice(FIRST) + ' ' + random.choice(LAST)

def date(r):
    d, p = r['Engagement_Date'], r['Date_Precision']
    if not d: return ''
    return str(d.year) if p == 'Year' else d.strftime('%d-%m-%Y')

rows = K.load()
# a made-up name must never be a real person's name
norm = lambda s: ' '.join(str(s or '').lower().split())
real = {norm(r['Name']) for r in rows}
out, used = [], set()
for r in rows:
    if r['Division'] not in PICK: continue
    circle, div, ranges = PICK[r['Division']]
    if ranges and r['Range'] not in ranges: continue
    n = name()
    while (div, n) in used or norm(n) in real: n = name()
    used.add((div, n))
    duty = '' if r['Cat'] in ('Unclear', 'Not reported') else DUTY.get(r['Sub'], 'Others')
    other = []
    for s in r['Also']:
        c = DUTY.get(s, 'Others')
        if c != duty and c not in other: other.append(c)
    place = PLACE.get(r['Posting_Location_Type'], '')
    pname = (r['Other_Place'] or '') if place not in ('', 'Beat') else ''
    mode = {'Direct': 'Direct', 'Through Agency': 'Through agency'}.get(r['Engagement_Mode'], '')
    out.append({'id': r['Record_ID'], 'cadre': 'CDL', 'circle': circle, 'division': div, 'name': n, 'mode': mode, 'agency': '',
                'date': date(r), 'district': '' if r['District'] in (None, 'Not stated') else r['District'],
                'range': 'Division HQ' if place == 'Division office' else '' if r['Range'] in (None, 'Not stated') else r['Range'],
                'beat': '' if place == 'Division office' else r['Beat'] or '',
                'place': place, 'placeName': pname, 'duty': duty, 'other': other,
                'pay': r['Monthly_Pay_Jul2026'], 'details': '' if duty != 'Others' else (r['Resolved'][:80]), 'flag': ''})

# two made-up double entries so the "problem" case can be seen
for div in ('Purulia', 'Jaldapara WL'):
    src = next(o for o in out if o['division'] == div and o['date'] and o['duty'])
    dup = dict(src, id=src['id'] + 'D', other=list(src['other']))
    src['flag'] = dup['flag'] = 'Possible double entry: same name and engagement date appear twice in this division.'
    out.insert(out.index(src) + 1, dup)

with open(OUT, 'w') as f:
    f.write('// Generated by scripts/make_demo.py. Names are made up; ranges, duties and pay follow real records.\n')
    f.write('window.CDL_DEMO = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
from collections import Counter
print(len(out), Counter(o['division'] for o in out), Counter(o['duty'] or '(blank)' for o in out))
